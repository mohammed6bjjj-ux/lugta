List<LegalDocument> _parseDocuments(String source) {
  final chunks = source
      .split(RegExp(r'^# ', multiLine: true))
      .map((chunk) => chunk.trim())
      .where((chunk) => chunk.isNotEmpty)
      .toList(growable: false);

  assert(
    chunks.length == _specs.length,
    'The embedded legal source must contain exactly seven documents.',
  );

  final count = chunks.length < _specs.length ? chunks.length : _specs.length;
  return List<LegalDocument>.generate(count, (index) {
    final spec = _specs[index];
    final lines = chunks[index].split('\n');
    if (lines.isNotEmpty) lines.removeAt(0);

    final sections = <LegalSection>[];
    var currentTitle = spec.defaultSectionTitle;
    final body = StringBuffer();

    void flushSection() {
      final text = body.toString().trim();
      if (text.isNotEmpty) {
        sections.add(LegalSection(title: currentTitle, body: text));
      }
      body.clear();
    }

    for (final sourceLine in lines) {
      final line = sourceLine.trimRight();
      if (line.startsWith('## ') || line.startsWith('### ')) {
        flushSection();
        currentTitle = line
            .replaceFirst(RegExp(r'^#{2,3}\s+'), '')
            .replaceFirst(RegExp(r'^\d+\.\s*'), '')
            .trim();
        continue;
      }
      body.writeln(line);
    }
    flushSection();

    return LegalDocument(
      id: spec.id,
      title: spec.title,
      summary: spec.summary,
      sections: List.unmodifiable(sections),
    );
  }, growable: false);
}

