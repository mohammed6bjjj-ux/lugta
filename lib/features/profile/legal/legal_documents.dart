/// المصدر المركزي للوثائق القانونية المعروضة داخل التطبيق.
abstract final class LegalDocuments {
  static const String version = '2';
  static const String effectiveDateIso = '2026-07-25';
  static const LegalLocalizedText effectiveDateLabel = LegalLocalizedText(
    ar: 'تاريخ النفاذ: 25 تموز 2026',
    ku: 'لە 25ی تەممووزی 2026 جێبەجێ دەبێت',
    en: 'Effective 25 July 2026',
  );

  static final List<LegalDocument> all = List.unmodifiable(
    _parseDocuments(_legalSource),
  );

  static LegalDocument? findById(String id) {
    for (final document in all) {
      if (document.id == id) return document;
    }
    return null;
  }

  static LegalDocument byId(String id) {
    final document = findById(id);
    if (document == null) {
      throw ArgumentError.value(id, 'id', 'Unknown legal document');
    }
    return document;
  }

  static LegalDocument get terms => byId(LegalDocumentIds.terms);
  static LegalDocument get privacy => byId(LegalDocumentIds.privacy);
  static LegalDocument get orders => byId(LegalDocumentIds.orders);
  static LegalDocument get earnings => byId(LegalDocumentIds.earnings);
  static LegalDocument get acceptableUse =>
      byId(LegalDocumentIds.acceptableUse);
  static LegalDocument get customerNotice =>
      byId(LegalDocumentIds.customerNotice);
  static LegalDocument get accountDeletion =>
      byId(LegalDocumentIds.accountDeletion);
}

